export const getLunarPeriodsForMonth = (month: number): LunarPeriod[] => {
  const monthStr = month.toString().padStart(2, "0");
  const yearMonth = `2026-${monthStr}`;
  return lunarCalendar2026.filter(
    (p) => p.startDate.startsWith(yearMonth) || p.endDate.startsWith(yearMonth)
  );
};

export const getCurrentLunarPeriod = (date: Date = new Date()): LunarPeriod | undefined => {
  const dateStr = date.toISOString().split("T")[0];
  return lunarCalendar2026.find(
    (p) => dateStr >= p.startDate && dateStr <= p.endDate
  );
};

